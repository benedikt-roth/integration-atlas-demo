#!/usr/bin/env python3
"""Generate and check a cross-referenced integration atlas; Python stdlib only."""

import argparse
import html
import json
import re
import sys
from pathlib import Path
from urllib.parse import unquote, urlsplit

ROOT = Path(__file__).resolve().parents[1]
NOTICE = '<!-- Generated by scripts/generate.py; edit catalog/catalog.json instead. -->\n\n'


def require(condition, message):
    if not condition:
        raise ValueError(message)


def local_file(path):
    file = (ROOT / path).resolve()
    require(file.is_relative_to(ROOT), f'Path leaves repository: {path}')
    require(file.is_file(), f'Missing file: {path}')
    return file


def validate(catalog):
    require(re.fullmatch(r'https://github\.com/[\w.-]+/[\w.-]+', catalog['repository_url']),
            'repository_url must be a GitHub repository URL without a trailing slash')
    require(re.fullmatch(r'[\w.-]+', catalog['branch']), 'Use a simple branch name')
    systems = {s['id']: s for s in catalog['systems']}
    require(len(systems) == len(catalog['systems']), 'Duplicate system IDs')
    require(systems, 'At least one system is required')
    for system in systems.values():
        require(re.fullmatch(r'[a-z]+(?:-[a-z]+)*', system['id']), 'Invalid system ID')
        require(system['boundary'] in ('internal', 'external'), 'Unknown system boundary')
        for field in ('name', 'owner', 'description'):
            require(isinstance(system[field], str) and system[field].strip(), f'Empty system {field}')
    ids = set()
    for interface in catalog['interfaces']:
        key = interface['id']
        require(re.fullmatch(r'IF-\d{3}', key), f'Invalid interface ID: {key}')
        require(key not in ids, f'Duplicate interface ID: {key}')
        ids.add(key)
        for endpoint in ('source', 'target'):
            require(interface[endpoint] in systems, f'{key}: unknown {endpoint} {interface[endpoint]}')
        for field in ('name', 'protocol', 'interaction', 'owner', 'status', 'artifact_type',
                      'summary', 'authentication', 'reliability'):
            require(isinstance(interface[field], str) and interface[field].strip(), f'{key}: empty {field}')
        require(isinstance(interface['notes'], list) and
                all(isinstance(note, str) for note in interface['notes']), f'{key}: notes must be strings')
        version = interface['deployed_version']
        require(re.fullmatch(r'\d+\.\d+\.\d+', version), f'{key}: use major.minor.patch')
        artifact = local_file(interface['artifact'])
        require(version in artifact.name, f'{key}: version must appear in artifact filename')
        if artifact.suffix == '.json':
            spec = json.loads(artifact.read_text())
            actual = spec['info']['version'] if 'openapi' in spec else spec['x-interface-version']
        elif artifact.suffix == '.md':
            match = re.search(r'^Contract version: \*\*([^*]+)\*\*$', artifact.read_text(), re.M)
            require(match, f'{key}: missing contract version marker')
            actual = match.group(1)
        else:
            raise ValueError(f'{key}: unsupported artifact format')
        require(actual == version, f'{key}: deployed version {version} differs from artifact {actual}')
    require(ids, 'At least one interface is required')


def cell(value):
    return str(value).replace('|', '\\|').replace('\n', ' ')


def label(value):
    return html.escape(value, quote=True).replace('\n', ' ')


def node(system_id):
    return 'S_' + system_id.replace('-', '_')


def render(catalog):
    systems = {s['id']: s for s in catalog['systems']}
    interfaces = catalog['interfaces']
    base = f"{catalog['repository_url']}/blob/{catalog['branch']}/"
    diagram = ['flowchart LR']
    for boundary, title in [('internal', 'Internal components'), ('external', 'External systems')]:
        diagram += [f'  subgraph {boundary}["{title}"]']
        for system in systems.values():
            if system['boundary'] == boundary:
                diagram.append(f'    {node(system["id"])}["{label(system["name"])}"]:::{boundary}')
        diagram.append('  end')
    for interface in interfaces:
        key = interface['id']
        ident = key.replace('-', '_')
        diagram += [f'  {ident}(["{key}<br/>{label(interface["name"])}"]):::interface',
                    f'  {node(interface["source"])} --> {ident} --> {node(interface["target"])}']
    for system in systems.values():
        diagram.append(f'  click {node(system["id"])} href "{base}docs/systems/{system["id"]}.md" "Open system details" _top')
    for interface in interfaces:
        key = interface['id']
        diagram.append(f'  click {key.replace("-", "_")} href "{base}docs/interfaces/{key}.md" "Open interface details" _top')
    diagram += ['  style internal fill:#eff6ff,stroke:#93c5fd,color:#172554',
                '  style external fill:#f8fafc,stroke:#cbd5e1,color:#111827',
                '  classDef internal fill:#dbeafe,stroke:#2563eb,color:#172554',
                '  classDef external fill:#e5e7eb,stroke:#64748b,color:#111827',
                '  classDef interface fill:#fef3c7,stroke:#d97706,color:#451a03']
    mermaid = '\n'.join(diagram) + '\n'

    rows = ['| Interface | Source → target | Protocol | Deployed version | Contract artifact |',
            '| --- | --- | --- | --- | --- |']
    for i in interfaces:
        rows.append(f'| [{i["id"]} — {cell(i["name"])}](docs/interfaces/{i["id"]}.md) '
                    f'| [{cell(systems[i["source"]]["name"])}](docs/systems/{i["source"]}.md) → '
                    f'[{cell(systems[i["target"]]["name"])}](docs/systems/{i["target"]}.md) '
                    f'| {cell(i["protocol"])} | {i["deployed_version"]} '
                    f'| [{cell(i["artifact_type"])}]({i["artifact"]}) |')
    readme = f'''# Integration Atlas — Mermaid cross-reference demo

A small documentation-as-code proof of concept: **two internal components, two external systems, five interfaces**.
All systems, owners, contracts, and versions are fictional examples.

**Start here:** click a yellow **IF-xxx** node to open its interface page, then follow its versioned contract artifact.
Click a blue or gray system node to see every incoming and outgoing interface.
The link table below provides the same navigation in any Markdown viewer.

## Integration landscape

```mermaid
{mermaid}```

Each yellow node represents a connection, not an extra running component. Arrows follow the primary request or data flow;
HTTP responses are implicit. IF-005 connects the two external systems directly.
Mermaid supports node hyperlinks; ordinary flowchart edges do not provide the same `click` directive.
The interface node makes every connection individually addressable.

## Interface catalog

{chr(10).join(rows)}

## Try the cross-references

1. Open [IF-003](docs/interfaces/IF-003.md): check deployed version **2.1.0** and open its OpenAPI artifact.
2. Follow its **Billing Worker** link: see both outgoing invoice calls and incoming events/webhooks.
3. Open [IF-005](docs/interfaces/IF-005.md): inspect the external CRM → ERP connection and its CSV contract.
4. Use the diagram nodes above and the table links to compare navigation in GitHub's renderer.
5. Follow [the review checklist](docs/review-checklist.md) to assess the approach in your own viewer.

## Maintain the repository

The [catalog](catalog/catalog.json) is the source for IDs, endpoints, deployed versions, owners, and operational notes.
The [versioned contracts](contracts/) contain the actual interface documentation artifacts.
The generator creates this README, the [reusable Mermaid source](docs/landscape.mmd), interface pages, and system backlinks.

```sh
python3 scripts/generate.py
python3 scripts/generate.py --check
```

Python 3.11+; no third-party dependencies. CI runs the check on pushes and pull requests.
It checks references, artifact versions, generated-file drift, and repository-local link destinations.
It does not validate a live deployment or perform full OpenAPI/JSON Schema conformance validation.

Read [the repository structure and tradeoffs](docs/approach.md) before adapting the demo.
See [verification results](docs/verification.md) for the checks performed on this proof of concept.
Native Mermaid click behavior depends on the hosting renderer; the Markdown table remains available.
'''
    outputs = {'README.md': NOTICE + readme, 'docs/landscape.mmd': mermaid}
    for i in interfaces:
        source, target = systems[i['source']], systems[i['target']]
        page = f'''# {i['id']} — {i['name']}

[Landscape and catalog](../../README.md) · [Catalog source](../../catalog/catalog.json)

{i['summary']}

| Field | Value |
| --- | --- |
| Stable interface ID | `{i['id']}` |
| Source | [{cell(source['name'])}](../systems/{source['id']}.md) ({source['boundary']}) |
| Target | [{cell(target['name'])}](../systems/{target['id']}.md) ({target['boundary']}) |
| Deployed contract version | **{i['deployed_version']}** |
| Status | {cell(i['status'])} |
| Protocol | {cell(i['protocol'])} |
| Operation / channel | {cell(i['interaction'])} |
| Integration owner | {cell(i['owner'])} |
| Contract artifact | [{cell(i['artifact_type'])} — {i['deployed_version']}](../../{i['artifact']}) |

## Authentication

{i['authentication']}

## Reliability and failure handling

{i['reliability']}

## Integration notes

{chr(10).join('- ' + note for note in i['notes'])}

The contract artifact is stored in this repository at a versioned path.
The deployed version is the example integration's selected contract version; it is not a measurement from a running system.
The stable interface page stays at the same path when that selected version changes.
'''
        outputs[f'docs/interfaces/{i["id"]}.md'] = NOTICE + page
    for system in systems.values():
        rows = ['| Direction | Interface | Other endpoint | Deployed version |', '| --- | --- | --- | --- |']
        for i in interfaces:
            if system['id'] not in (i['source'], i['target']):
                continue
            outgoing = system['id'] == i['source']
            other = systems[i['target'] if outgoing else i['source']]
            rows.append(f'| {"Outgoing" if outgoing else "Incoming"} '
                        f'| [{i["id"]} — {cell(i["name"])}](../interfaces/{i["id"]}.md) '
                        f'| [{cell(other["name"])}]({other["id"]}.md) | {i["deployed_version"]} |')
        outputs[f'docs/systems/{system["id"]}.md'] = NOTICE + f'''# {system['name']}

[Landscape and catalog](../../README.md)

{system['description']}

Boundary: **{system['boundary']}**. Owner: **{system['owner']}**.

## Connected interfaces

{chr(10).join(rows)}

Directions follow the primary request or data flow. HTTP responses use the same interface.
'''
    return outputs


def check_links():
    count = 0
    for file in ROOT.rglob('*.md'):
        if '.git' in file.relative_to(ROOT).parts:
            continue
        text = re.sub(r'```.*?```', '', file.read_text(), flags=re.S)
        for destination in re.findall(r'\[[^\]]*\]\(([^\s)]+)\)', text):
            url = urlsplit(destination)
            if url.scheme or url.netloc or not url.path:
                continue
            path = (file.parent / unquote(url.path)).resolve()
            require(path.is_relative_to(ROOT) and path.exists(), f'{file.relative_to(ROOT)}: broken link {destination}')
            count += 1
    return count


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='Fail on drift without writing files')
    args = parser.parse_args()
    catalog = json.loads((ROOT / 'catalog/catalog.json').read_text())
    validate(catalog)
    outputs = render(catalog)
    for path, text in outputs.items():
        file = ROOT / path
        if args.check:
            require(file.is_file() and file.read_text() == text, f'Stale generated file: {path}; run python3 scripts/generate.py')
        else:
            file.parent.mkdir(parents=True, exist_ok=True)
            file.write_text(text)
    expected = set(outputs)
    for directory in ('docs/interfaces', 'docs/systems'):
        for file in (ROOT / directory).glob('*.md'):
            require(file.relative_to(ROOT).as_posix() in expected, f'Orphaned generated page: {file.relative_to(ROOT)}; remove it explicitly')
    count = check_links()
    print(f'OK: {len(catalog["systems"])} systems, {len(catalog["interfaces"])} interfaces, '
          f'{len(outputs)} generated files, {count} local Markdown links.')


if __name__ == '__main__':
    try:
        main()
    except (ValueError, KeyError, TypeError) as error:
        print(f'ERROR: {error}', file=sys.stderr)
        sys.exit(1)
