#!/usr/bin/env python3
"""Generate and check a cross-referenced integration atlas; Python stdlib only."""

import argparse
import html
import json
import posixpath
import re
import sys
from pathlib import Path, PurePosixPath
from urllib.parse import quote, unquote, urlsplit

ROOT = Path(__file__).resolve().parents[1]
NOTICE = '<!-- Generated by scripts/generate.py; edit catalog/catalog.json instead. -->\n\n'


def require(condition, message):
    if not condition:
        raise ValueError(message)


def local_file(path):
    file = (ROOT / path).resolve()
    require(file.is_relative_to(ROOT), f'Path leaves repository: {path}')
    require(file.is_file(), f'Missing file: {path}')
    return file


def validate(catalog):
    require(re.fullmatch(r'https://github\.com/[\w.-]+/[\w.-]+', catalog['repository_url']),
            'repository_url must be a GitHub repository URL without a trailing slash')
    require(re.fullmatch(r'[\w.-]+', catalog['branch']), 'Use a simple branch name')
    systems = {s['id']: s for s in catalog['systems']}
    require(len(systems) == len(catalog['systems']), 'Duplicate system IDs')
    require(systems, 'At least one system is required')
    for system in systems.values():
        require(re.fullmatch(r'[a-z]+(?:-[a-z]+)*', system['id']), 'Invalid system ID')
        require(system['boundary'] in ('internal', 'external'), 'Unknown system boundary')
        for field in ('name', 'owner', 'description'):
            require(isinstance(system[field], str) and system[field].strip(), f'Empty system {field}')
    ids = set()
    for interface in catalog['interfaces']:
        key = interface['id']
        require(re.fullmatch(r'IF-\d{3}', key), f'Invalid interface ID: {key}')
        require(key not in ids, f'Duplicate interface ID: {key}')
        ids.add(key)
        for endpoint in ('source', 'target'):
            require(interface[endpoint] in systems, f'{key}: unknown {endpoint} {interface[endpoint]}')
        for field in ('name', 'protocol', 'interaction', 'owner', 'status', 'artifact_type',
                      'summary', 'authentication', 'reliability'):
            require(isinstance(interface[field], str) and interface[field].strip(), f'{key}: empty {field}')
        require(isinstance(interface['notes'], list) and
                all(isinstance(note, str) for note in interface['notes']), f'{key}: notes must be strings')
        version = interface['deployed_version']
        require(re.fullmatch(r'\d+\.\d+\.\d+', version), f'{key}: use major.minor.patch')
        artifact = local_file(interface['artifact'])
        require(version in artifact.name, f'{key}: version must appear in artifact filename')
        if artifact.suffix == '.json':
            spec = json.loads(artifact.read_text())
            actual = spec['info']['version'] if 'openapi' in spec else spec['x-interface-version']
        elif artifact.suffix == '.md':
            match = re.search(r'^Contract version: \*\*([^*]+)\*\*$', artifact.read_text(), re.M)
            require(match, f'{key}: missing contract version marker')
            actual = match.group(1)
        else:
            raise ValueError(f'{key}: unsupported artifact format')
        require(actual == version, f'{key}: deployed version {version} differs from artifact {actual}')
    require(ids, 'At least one interface is required')
    validate_views(catalog, ids)


def view_interfaces(view):
    if view['kind'] == 'overview':
        return view['interface_ids']
    return list(dict.fromkeys(step['interface_id'] for step in view['steps']))


def validate_views(catalog, interface_ids):
    views = catalog.get('views', [])
    require(isinstance(views, list), 'views must be a list')
    seen = set()
    for view in views:
        require(isinstance(view, dict), 'Each view must be an object')
        key = view.get('id')
        require(isinstance(key, str) and re.fullmatch(r'[a-z0-9]+(?:-[a-z0-9]+)*', key),
                'View IDs must be filename-safe lowercase slugs')
        require(key not in seen, f'Duplicate view ID: {key}')
        seen.add(key)
        for field in ('title', 'summary'):
            require(isinstance(view.get(field), str) and view[field].strip(), f'{key}: empty {field}')
        require(view.get('kind') in ('overview', 'scenario'), f'{key}: unsupported view kind')
        if view['kind'] == 'overview':
            require('steps' not in view, f'{key}: overview views select interface_ids, not steps')
            selected = view.get('interface_ids')
            require(isinstance(selected, list) and selected, f'{key}: select at least one interface')
            require(all(isinstance(i, str) for i in selected), f'{key}: interface IDs must be strings')
            require(len(selected) == len(set(selected)), f'{key}: duplicate overview interface')
        else:
            require('interface_ids' not in view, f'{key}: scenario membership is derived from steps')
            steps = view.get('steps')
            require(isinstance(steps, list) and steps, f'{key}: provide at least one step')
            for number, step in enumerate(steps, 1):
                context = f'{key} step {number}'
                require(isinstance(step, dict), f'{context}: step must be an object')
                require(isinstance(step.get('interface_id'), str), f'{context}: interface_id is required')
                require(step.get('direction', 'forward') in ('forward', 'reverse'),
                        f'{context}: direction must be forward or reverse')
                annotation = step.get('annotation')
                require(isinstance(annotation, dict), f'{context}: annotation must be an object')
                require(isinstance(annotation.get('text'), str) and annotation['text'].strip(),
                        f'{context}: annotation text is required')
                if 'target' in annotation:
                    target = annotation['target']
                    require(isinstance(target, str) and target, f'{context}: annotation target is required')
                    url = urlsplit(target)
                    path = PurePosixPath(target)
                    require(not (url.scheme or url.netloc or url.query or url.fragment)
                            and not path.is_absolute() and '..' not in path.parts
                            and '\\' not in target and path.as_posix() == target
                            and path.suffix == '.md'
                            and not any(ord(c) < 32 for c in target),
                            f'{context}: target must be a repository-relative Markdown page path')
            selected = [step['interface_id'] for step in steps]
        for interface_id in selected:
            require(interface_id in interface_ids, f'{key}: unknown interface {interface_id}')

    # Generated pages can be linked before their first generation.
    generated = {'README.md'}
    generated.update(f'docs/interfaces/{i}.md' for i in interface_ids)
    generated.update(f'docs/systems/{s["id"]}.md' for s in catalog['systems'])
    generated.update(f'docs/views/{v["id"]}.md' for v in views)
    for view in views:
        for step in view.get('steps', []):
            target = step['annotation'].get('target')
            if target:
                file = (ROOT / target).resolve()
                require(file.is_relative_to(ROOT), f'{view["id"]}: annotation target leaves repository')
                require(file.is_file() or target in generated,
                        f'{view["id"]}: missing annotation target {target}')


def cell(value):
    return str(value).replace('|', '\\|').replace('\n', ' ')


def label(value):
    # Mermaid entities survive GitHub's HTML-decoding step before parsing.
    entities = {'#': '#35;', ';': '#59;', '&': '#38;', '<': '#60;', '>': '#62;',
                '"': '#34;', "'": '#39;', '|': '#124;'}
    return ''.join(entities.get(c, ' ' if c in '\n\r' else c) for c in value)


def node(system_id):
    return 'S_' + system_id.replace('-', '_')


def markdown_text(value):
    text = re.sub(r'([\\`*_\[\]])', r'\\\1', html.escape(str(value), quote=False))
    return cell(text)


def page_link(text, target, page):
    destination = quote(posixpath.relpath(target, posixpath.dirname(page) or '.'), safe='/')
    return f'[{markdown_text(text)}]({destination})'


def github_link(catalog, target):
    return f'{catalog["repository_url"]}/blob/{catalog["branch"]}/{quote(target, safe="/")}'


def connections(catalog, view=None):
    interfaces = {i['id']: i for i in catalog['interfaces']}
    if view and view['kind'] == 'scenario':
        result = []
        for number, step in enumerate(view['steps'], 1):
            interface = interfaces[step['interface_id']]
            reverse = step.get('direction', 'forward') == 'reverse'
            source, target = interface['source'], interface['target']
            if reverse:
                source, target = target, source
            result.append(dict(interface=interface, source=source, target=target,
                               number=number, node=f'STEP_{number:03}', reverse=reverse,
                               annotation=step['annotation']))
        return result
    selected = view_interfaces(view) if view else list(interfaces)
    return [dict(interface=interfaces[key], source=interfaces[key]['source'],
                 target=interfaces[key]['target'], node=key.replace('-', '_'), reverse=False)
            for key in selected]


def flowchart(catalog, entries):
    systems = {s['id']: s for s in catalog['systems']}
    included = {e[endpoint] for e in entries for endpoint in ('source', 'target')}
    diagram = ['flowchart LR']
    for boundary, title in [('internal', 'Internal components'), ('external', 'External systems')]:
        members = [s for s in systems.values() if s['boundary'] == boundary and s['id'] in included]
        if not members:
            continue
        diagram += [f'  subgraph {boundary}["{title}"]']
        for system in members:
            diagram.append(f'    {node(system["id"])}["{label(system["name"])}"]:::{boundary}')
        diagram.append('  end')
    for entry in entries:
        interface = entry['interface']
        ident = entry['node']
        title = interface['id']
        edge_label = ''
        if 'number' in entry:
            title = f'{entry["number"]}. {title}'
            annotation = entry['annotation']
            text = label(f'{entry["number"]}. {annotation["text"]}')
            if annotation.get('target'):
                href = html.escape(github_link(catalog, annotation['target']), quote=True)
                text = f"<a href='{href}'>{text}</a>"
            edge_label = f'|"{text}"|'
        arrow = '-.->' if entry['reverse'] else '-->'
        diagram += [f'  {ident}(["{title}<br/>{label(interface["name"])}"]):::interface',
                    f'  {node(entry["source"])} {arrow}{edge_label} {ident} {arrow} {node(entry["target"])}']
    for system in systems.values():
        if system['id'] in included:
            href = github_link(catalog, f'docs/systems/{system["id"]}.md')
            diagram.append(f'  click {node(system["id"])} href "{href}" "Open system details" _top')
    for entry in entries:
        href = github_link(catalog, f'docs/interfaces/{entry["interface"]["id"]}.md')
        diagram.append(f'  click {entry["node"]} href "{href}" "Open interface details" _top')
    for boundary, color in [('internal', 'fill:#eff6ff,stroke:#93c5fd,color:#172554'),
                            ('external', 'fill:#f8fafc,stroke:#cbd5e1,color:#111827')]:
        if any(systems[s]['boundary'] == boundary for s in included):
            diagram.append(f'  style {boundary} {color}')
    diagram += ['  classDef internal fill:#dbeafe,stroke:#2563eb,color:#172554',
                '  classDef external fill:#e5e7eb,stroke:#64748b,color:#111827',
                '  classDef interface fill:#fef3c7,stroke:#d97706,color:#451a03']
    return '\n'.join(diagram) + '\n'


def sequence_text(value):
    return label(value)


def sequence(catalog, entries):
    systems = {s['id']: s for s in catalog['systems']}
    participants = list(dict.fromkeys(e[p] for e in entries for p in ('source', 'target')))
    lines = ['sequenceDiagram', '  autonumber']
    for key in participants:
        lines.append(f'  participant {node(key)} as {sequence_text(systems[key]["name"])}')
    for entry in entries:
        arrow = '-->>' if entry['reverse'] else '->>'
        message = sequence_text(f'{entry["interface"]["id"]} — {entry["annotation"]["text"]}')
        lines.append(f'  {node(entry["source"])}{arrow}{node(entry["target"])}: {message}')
    return '\n'.join(lines) + '\n'


def interface_table(catalog, interfaces, page):
    systems = {s['id']: s for s in catalog['systems']}
    rows = ['| Interface | Source → target | Protocol | Deployed version | Contract artifact |',
            '| --- | --- | --- | --- | --- |']
    for i in interfaces:
        interface = page_link(f'{i["id"]} — {i["name"]}', f'docs/interfaces/{i["id"]}.md', page)
        source = page_link(systems[i['source']]['name'], f'docs/systems/{i["source"]}.md', page)
        target = page_link(systems[i['target']]['name'], f'docs/systems/{i["target"]}.md', page)
        artifact = page_link(i['artifact_type'], i['artifact'], page)
        rows.append(f'| {interface} | {source} → {target} '
                    f'| {cell(i["protocol"])} | {i["deployed_version"]} '
                    f'| {artifact} |')
    return '\n'.join(rows)


def step_table(catalog, entries, page):
    systems = {s['id']: s for s in catalog['systems']}
    rows = ['| Step | Source → target | Annotation | Interface | Deployed version | Contract artifact |',
            '| --- | --- | --- | --- | --- | --- |']
    for entry in entries:
        i = entry['interface']
        annotation = entry['annotation']
        text = (page_link(annotation['text'], annotation['target'], page)
                if annotation.get('target') else markdown_text(annotation['text']))
        source = page_link(systems[entry['source']]['name'], f'docs/systems/{entry["source"]}.md', page)
        target = page_link(systems[entry['target']]['name'], f'docs/systems/{entry["target"]}.md', page)
        interface = page_link(i['id'], f'docs/interfaces/{i["id"]}.md', page)
        artifact = page_link(i['artifact_type'], i['artifact'], page)
        rows.append(f'| {entry["number"]} | {source} → {target} | {text} | {interface} '
                    f'| {i["deployed_version"]} | {artifact} |')
    return '\n'.join(rows)


def backlinks(catalog, page, interface_id=None, system_id=None):
    interfaces = {i['id']: i for i in catalog['interfaces']}
    links = []
    for view in catalog.get('views', []):
        selected = view_interfaces(view)
        members = {interfaces[i][p] for i in selected for p in ('source', 'target')}
        if interface_id in selected or system_id in members:
            links.append('- ' + page_link(view['title'], f'docs/views/{view["id"]}.md', page))
    return '\n## Used in views\n\n' + '\n'.join(links) + '\n' if links else ''


def render_view(catalog, view):
    page = f'docs/views/{view["id"]}.md'
    entries = connections(catalog, view)
    text = NOTICE + f'''# {view['title']}

[Full landscape and view index](../../README.md) · [View definition](../../catalog/catalog.json)

{view['summary']}

## Component map

```mermaid
{flowchart(catalog, entries)}```
'''
    if view['kind'] == 'scenario':
        text += f'''
Numbers identify steps in this scenario, not separate interface definitions. Click a yellow
interface node for its canonical details, or a linked connection annotation for its reference page.
Dashed connections are reverse messages on the same interface.

## Sequence diagram

```mermaid
{sequence(catalog, entries)}```

The step list drives numbering in both diagrams. Responses are explicit reverse steps.
Arrows describe this linear data flow; they do not simulate transport timing.
GitHub sequence message labels do not support these annotation hyperlinks; use the linked annotations in the table below.

## Steps and references

{step_table(catalog, entries, page)}
'''
    else:
        text += f'''
This overview selects interfaces without implying execution order. Click an interface node for its details.

## Selected interfaces

{interface_table(catalog, [e['interface'] for e in entries], page)}
'''
    return text


def render(catalog):
    systems = {s['id']: s for s in catalog['systems']}
    interfaces = catalog['interfaces']
    mermaid = flowchart(catalog, connections(catalog))
    views = ''
    if catalog.get('views'):
        rows = ['## Focused views', '', '| View | Kind | Purpose |', '| --- | --- | --- |']
        for view in catalog['views']:
            link = page_link(view['title'], f'docs/views/{view["id"]}.md', 'README.md')
            rows.append(f'| {link} | {view["kind"]} | {cell(view["summary"])} |')
        views = '\n'.join(rows) + '\n\n'
    readme = f'''# Integration Atlas — Mermaid cross-reference demo

A small documentation-as-code proof of concept: **two internal components, two external systems, five interfaces**.
All systems, owners, contracts, and versions are fictional examples.

**Start here:** click a yellow **IF-xxx** node to open its interface page, then follow its versioned contract artifact.
Click a blue or gray system node to see every incoming and outgoing interface.
The link table below provides the same navigation in any Markdown viewer.

{views}## Integration landscape

```mermaid
{mermaid}```

Each yellow node represents a connection, not an extra running component. Arrows follow the primary request or data flow;
HTTP responses are implicit. IF-005 connects the two external systems directly.
Mermaid supports node hyperlinks; ordinary flowchart edges do not provide the same `click` directive.
The interface node makes every connection individually addressable.

## Interface catalog

{interface_table(catalog, interfaces, 'README.md')}

## Try the cross-references

1. Open [IF-003](docs/interfaces/IF-003.md): check deployed version **2.1.0** and open its OpenAPI artifact.
2. Follow its **Billing Worker** link: see both outgoing invoice calls and incoming events/webhooks.
3. Open [IF-005](docs/interfaces/IF-005.md): inspect the external CRM → ERP connection and its CSV contract.
4. Use the diagram nodes above and the table links to compare navigation in GitHub's renderer.
5. Follow [the review checklist](docs/review-checklist.md) to assess the approach in your own viewer.

## Maintain the repository

The [catalog](catalog/catalog.json) is the source for IDs, endpoints, deployed versions, owners, and operational notes.
The [versioned contracts](contracts/) contain the actual interface documentation artifacts.
The generator creates this README, the [reusable Mermaid source](docs/landscape.mmd), interface pages, and system backlinks.
Named views select existing interfaces. Scenarios add ordered steps, linked annotations, and explicit responses;
their component maps, sequence diagrams, and step tables come from the same step list.

```sh
python3 scripts/generate.py
python3 scripts/generate.py --check
python3 -m unittest discover -s tests -v
```

Python 3.11+; no third-party dependencies. CI runs the check and tests on pushes and pull requests.
It checks references, artifact versions, generated-file drift, and repository-local link destinations.
It does not validate a live deployment or perform full OpenAPI/JSON Schema conformance validation.

Read [the repository structure and tradeoffs](docs/approach.md) before adapting the demo.
See [verification results](docs/verification.md) for the checks performed on this proof of concept.
Native Mermaid click behavior depends on the hosting renderer; the Markdown table remains available.
'''
    outputs = {'README.md': NOTICE + readme, 'docs/landscape.mmd': mermaid}
    outputs.update({f'docs/views/{view["id"]}.md': render_view(catalog, view)
                    for view in catalog.get('views', [])})
    for i in interfaces:
        source, target = systems[i['source']], systems[i['target']]
        page = f'''# {i['id']} — {i['name']}

[Landscape and catalog](../../README.md) · [Catalog source](../../catalog/catalog.json)

{i['summary']}

| Field | Value |
| --- | --- |
| Stable interface ID | `{i['id']}` |
| Source | [{cell(source['name'])}](../systems/{source['id']}.md) ({source['boundary']}) |
| Target | [{cell(target['name'])}](../systems/{target['id']}.md) ({target['boundary']}) |
| Deployed contract version | **{i['deployed_version']}** |
| Status | {cell(i['status'])} |
| Protocol | {cell(i['protocol'])} |
| Operation / channel | {cell(i['interaction'])} |
| Integration owner | {cell(i['owner'])} |
| Contract artifact | [{cell(i['artifact_type'])} — {i['deployed_version']}](../../{i['artifact']}) |

## Authentication

{i['authentication']}

## Reliability and failure handling

{i['reliability']}

## Integration notes

{chr(10).join('- ' + note for note in i['notes'])}

The contract artifact is stored in this repository at a versioned path.
The deployed version is the example integration's selected contract version; it is not a measurement from a running system.
The stable interface page stays at the same path when that selected version changes.
'''
        path = f'docs/interfaces/{i["id"]}.md'
        outputs[path] = NOTICE + page + backlinks(catalog, path, interface_id=i['id'])
    for system in systems.values():
        rows = ['| Direction | Interface | Other endpoint | Deployed version |', '| --- | --- | --- | --- |']
        for i in interfaces:
            if system['id'] not in (i['source'], i['target']):
                continue
            outgoing = system['id'] == i['source']
            other = systems[i['target'] if outgoing else i['source']]
            rows.append(f'| {"Outgoing" if outgoing else "Incoming"} '
                        f'| [{i["id"]} — {cell(i["name"])}](../interfaces/{i["id"]}.md) '
                        f'| [{cell(other["name"])}]({other["id"]}.md) | {i["deployed_version"]} |')
        outputs[f'docs/systems/{system["id"]}.md'] = NOTICE + f'''# {system['name']}

[Landscape and catalog](../../README.md)

{system['description']}

Boundary: **{system['boundary']}**. Owner: **{system['owner']}**.

## Connected interfaces

{chr(10).join(rows)}

Directions follow the primary request or data flow. HTTP responses use the same interface.
''' + backlinks(catalog, f'docs/systems/{system["id"]}.md', system_id=system['id'])
    return outputs


def check_links():
    count = 0
    for file in ROOT.rglob('*.md'):
        if '.git' in file.relative_to(ROOT).parts:
            continue
        text = re.sub(r'```.*?```', '', file.read_text(), flags=re.S)
        for destination in re.findall(r'\[[^\]]*\]\(([^\s)]+)\)', text):
            url = urlsplit(destination)
            if url.scheme or url.netloc or not url.path:
                continue
            path = (file.parent / unquote(url.path)).resolve()
            require(path.is_relative_to(ROOT) and path.exists(), f'{file.relative_to(ROOT)}: broken link {destination}')
            count += 1
    return count


def write_outputs(outputs, check=False):
    expected = set(outputs)
    for directory in ('docs/interfaces', 'docs/systems', 'docs/views'):
        for file in (ROOT / directory).glob('*.md'):
            require(file.relative_to(ROOT).as_posix() in expected, f'Orphaned generated page: {file.relative_to(ROOT)}; remove it explicitly')
    for path, text in outputs.items():
        file = ROOT / path
        if check:
            require(file.is_file() and file.read_text() == text, f'Stale generated file: {path}; run python3 scripts/generate.py')
        else:
            file.parent.mkdir(parents=True, exist_ok=True)
            file.write_text(text)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='Fail on drift without writing files')
    args = parser.parse_args()
    catalog = json.loads((ROOT / 'catalog/catalog.json').read_text())
    validate(catalog)
    outputs = render(catalog)
    write_outputs(outputs, check=args.check)
    count = check_links()
    print(f'OK: {len(catalog["systems"])} systems, {len(catalog["interfaces"])} interfaces, '
          f'{len(catalog.get("views", []))} views, '
          f'{len(outputs)} generated files, {count} local Markdown links.')


if __name__ == '__main__':
    try:
        main()
    except (ValueError, KeyError, TypeError) as error:
        print(f'ERROR: {error}', file=sys.stderr)
        sys.exit(1)
