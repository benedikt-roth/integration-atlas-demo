import json
from pathlib import Path
import sys
import unittest

sys.path.insert(0, str(Path(__file__).resolve().parents[1] / 'scripts'))
from render_readme import REPOSITORY, make_readme, source_links


class RenderedPageTests(unittest.TestCase):
    def setUp(self):
        self.catalog = json.loads((REPOSITORY / 'catalog/catalog.json').read_text())

    def test_source_references_do_not_point_at_missing_output_branch_pages(self):
        table = source_links('[Interface](docs/interfaces/IF-003.md) [Mapping](docs/notes/invoice-mapping.md)', self.catalog)
        self.assertIn('/blob/main/docs/interfaces/IF-003.md', table)
        self.assertIn('/blob/main/docs/notes/invoice-mapping.md', table)
        external = '[External](https://example.com/page)'
        self.assertEqual(source_links(external, self.catalog), external)

    def test_page_preserves_native_export_and_explicit_response_references(self):
        native = '<!-- Generated by LikeC4 -->\n# default\n\n### Landscape\n```mermaid\ngraph LR\nA-->B\n```\n'
        page = make_readme(self.catalog, native, 'a' * 40)
        self.assertNotIn('# default', page)
        self.assertIn('### Landscape', page)
        self.assertIn('graph LR\nA-->B', page)
        self.assertIn('autonumber', page)
        self.assertIn('S_erp-->>S_billing_worker: IF-003 — Return invoice ID', page)
        self.assertIn('[IF-003](https://github.com/benedikt-roth/integration-atlas-demo/blob/main/docs/interfaces/IF-003.md)', page)
        self.assertIn('/tree/' + 'a' * 40 + '/likec4-poc', page)
        self.assertIn('(index.html?raw=true)', page)

    def test_build_report_uses_current_contract_and_annotation_destinations(self):
        page = make_readme(self.catalog, '# default\n')
        self.assertIn('/contracts/erp/invoices-2.1.0.openapi.json', page)
        self.assertIn('[Create invoice using the mapping rules](https://github.com/benedikt-roth/integration-atlas-demo/blob/main/docs/notes/invoice-mapping.md)', page)
        self.assertIn('known reverse-step association issue', page)


if __name__ == '__main__':
    unittest.main()
