#!/usr/bin/env python3
"""Adapt the existing catalog into LikeC4 without maintaining another model."""

import argparse
import importlib.util
import json
from pathlib import Path
import sys

POC = Path(__file__).resolve().parents[1]
REPOSITORY = POC.parent
spec = importlib.util.spec_from_file_location('atlas_generator', REPOSITORY / 'scripts/generate.py')
atlas = importlib.util.module_from_spec(spec)
spec.loader.exec_module(atlas)


def identifier(value):
    return value.lower().replace('-', '_')


def string(value):
    return json.dumps(value, ensure_ascii=False)


def markdown(value):
    # LikeC4 distinguishes triple-quoted Markdown from plain quoted text.
    delimiter = '"""' if '"""' not in value else "'''"
    atlas.require(delimiter not in value, 'Notes contain both triple-quote delimiters')
    return delimiter + '\n' + '\n'.join('        ' + line for line in value.splitlines()) + '\n      ' + delimiter


def url(catalog, path):
    return atlas.github_link(catalog, path)


def render(catalog):
    interfaces = {i['id']: i for i in catalog['interfaces']}
    lines = [
        '// Generated by likec4-poc/scripts/generate.py; do not edit.',
        '// Source of truth: catalog/catalog.json at the repository root.',
        '', 'specification {',
        '  element internal_component { style { color blue } }',
        '  element external_system { style { color gray } }',
    ]
    for key in interfaces:
        lines.append(f'  relationship {identifier(key)} {{ line solid }}')
    lines += ['}', '', 'model {']
    for system in catalog['systems']:
        kind = 'internal_component' if system['boundary'] == 'internal' else 'external_system'
        documentation = url(catalog, f'docs/systems/{system["id"]}.md')
        lines += [
            f'  {identifier(system["id"])} = {kind} {string(system["name"])} {{',
            f'    description {string(system["description"])}',
            f'    link {documentation} "System documentation"',
            f'    metadata {{ owner {string(system["owner"])} }}',
            '  }',
        ]
    for interface in interfaces.values():
        key = interface['id']
        lines += [
            f'  {identifier(interface["source"])} -[{identifier(key)}]-> {identifier(interface["target"])} {string(key + " — " + interface["name"])} {{',
            f'    technology {string(interface["protocol"])}',
            f'    description {string(interface["summary"])}',
            f'    link {url(catalog, f"docs/interfaces/{key}.md")} "Canonical interface details"',
            f'    link {url(catalog, interface["artifact"])} {string("Contract " + interface["deployed_version"])}',
            '    metadata {',
            f'      interfaceId {string(key)}',
            f'      deployedVersion {string(interface["deployed_version"])}',
            f'      owner {string(interface["owner"])}',
            '    }',
            '  }',
        ]
    landscape_description = (f"The same {len(catalog['systems'])} systems and {len(interfaces)} interfaces "
                             'as the Mermaid POC. Select a relationship to inspect its metadata and documentation links.')
    lines += [
        '}', '', 'views {', '  view index {',
        '    title "Integration landscape"',
        f'    description {string(landscape_description)}',
        '    include *', '    autoLayout LeftRight', '  }',
    ]
    for view in catalog.get('views', []):
        key = identifier(view['id'])
        documentation = url(catalog, f'docs/views/{view["id"]}.md')
        prefix = 'dynamic ' if view['kind'] == 'scenario' else ''
        lines += [f'  {prefix}view {key} {{',
                  f'    title {string(view["title"])}',
                  f'    description {string(view["summary"])}',
                  f'    link {documentation} "Markdown counterpart"']
        if view['kind'] == 'overview':
            condition = ' or '.join(f'metadata.interfaceId is {string(i)}' for i in view['interface_ids'])
            lines += [f'    include * -> * where {condition}', '    autoLayout LeftRight']
        else:
            for step in view['steps']:
                interface = interfaces[step['interface_id']]
                interface_page = url(catalog, f'docs/interfaces/{interface["id"]}.md')
                source, target = identifier(interface['source']), identifier(interface['target'])
                reverse = step.get('direction', 'forward') == 'reverse'
                arrow = '<-' if reverse else f'-[{identifier(interface["id"])}]->'
                annotation = step['annotation']
                notes = [
                    f'**{interface["id"]} — {interface["name"]}**',
                    '',
                    f'Selected contract version: **{interface["deployed_version"]}**.',
                    '',
                    f'- [Canonical interface details]({interface_page})',
                    f'- [Contract artifact]({url(catalog, interface["artifact"])})',
                ]
                annotation_text = atlas.markdown_text(annotation['text'])
                if annotation.get('target'):
                    annotation_text = f'[{annotation_text}]({url(catalog, annotation["target"])})'
                notes += ['', '**Annotation:** ' + annotation_text]
                lines += [
                    f'    {source} {arrow} {target} {string(interface["id"] + " — " + annotation["text"])} {{',
                    f'      technology {string(interface["protocol"])}',
                    f'      description {string(interface["summary"])}',
                    f'      line {"dashed" if reverse else "solid"}',
                    f'      notes {markdown(chr(10).join(notes))}',
                    '    }',
                ]
        lines.append('  }')
    lines += ['}', '']
    return '\n'.join(lines)


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true', help='Fail on stale generated LikeC4 source')
    args = parser.parse_args()
    catalog = json.loads((REPOSITORY / 'catalog/catalog.json').read_text())
    atlas.validate(catalog)
    text = render(catalog)
    file = POC / 'src/atlas.c4'
    if args.check:
        atlas.require(file.is_file() and file.read_text() == text,
                      'Stale LikeC4 source; run npm run generate in likec4-poc')
    else:
        file.parent.mkdir(parents=True, exist_ok=True)
        file.write_text(text)
    print(f'OK: LikeC4 source matches {len(catalog["systems"])} systems, '
          f'{len(catalog["interfaces"])} interfaces, and {len(catalog.get("views", []))} focused views.')


if __name__ == '__main__':
    try:
        main()
    except (ValueError, KeyError, TypeError) as error:
        print(f'ERROR: {error}', file=sys.stderr)
        sys.exit(1)
