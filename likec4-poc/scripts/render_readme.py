#!/usr/bin/env python3
"""Add a GitHub-renderable page to the same output as the interactive build."""

import json
import os
from pathlib import Path
import re
import shutil
import subprocess
import tempfile
from urllib.parse import unquote, urlsplit

from generate import POC, REPOSITORY, atlas, url


def source_links(markdown, catalog):
    """Published output has its own branch; documentation belongs to the source."""
    def destination(match):
        target = match.group(1)
        parsed = urlsplit(target)
        if parsed.scheme or parsed.netloc or not parsed.path:
            return match.group(0)
        return '](' + url(catalog, unquote(parsed.path)) + ')'
    return re.sub(r'\]\(([^)]+)\)', destination, markdown)


def make_readme(catalog, exported, source_sha=''):
    base = catalog['repository_url']
    ref = source_sha if re.fullmatch(r'[0-9a-f]{40}', source_sha) else catalog['branch']
    # Keep native exported diagrams, replacing only the generic project heading.
    exported = re.sub(r'^# [^\n]+\n', '', exported, count=1, flags=re.M).strip()
    sections = [f'''<!-- Generated by npm run build. Do not edit on the rendered branch. -->
# LikeC4 — rendered demonstration

[Source used for this build]({base}/tree/{ref}/likec4-poc) ·
[Download the interactive HTML](index.html?raw=true)

This page renders directly in GitHub. It is generated after the LikeC4 build and
published here automatically when the build on `main` succeeds. The native
LikeC4-exported diagrams appear below, followed by the shared interface catalog.

For the full interactive viewer, download `index.html`, or clone this branch and
serve its directory with `python3 -m http.server 3000`. Open the local address
printed by that server. The HTML contains the application's scripts and styles;
the standalone file was also tested over a local HTTP server.
''']
    for view in catalog.get('views', []):
        if view['kind'] != 'scenario':
            continue
        entries = atlas.connections(catalog, view)
        sections.append(f'''## {view['title']} — numbered flow

{view['summary']}

```mermaid
{atlas.sequence(catalog, entries)}```

### Annotations and interface references

{source_links(atlas.step_table(catalog, entries, 'README.md'), catalog)}
''')
    sections += [
        '## Native LikeC4 diagram exports\n\n' + exported,
        '## Shared interface catalog\n\n' + source_links(atlas.interface_table(catalog, catalog['interfaces'], 'README.md'), catalog),
        f'''## Demo notes

The interactive viewer exposes references through its step notes. LikeC4 1.60.0
has a known reverse-step association issue in this example: the return arrow's
native relationship lookup selects IF-004. The explicit canonical links above
and in step notes correctly reference IF-003. See the
[evaluation finding]({base}/blob/{catalog['branch']}/likec4-poc/README.md#evaluation-finding-reverse-step-relationship-matching).

All interface definitions and scenario steps are maintained in the source
catalog. This branch contains generated build output.
''',
    ]
    return '\n\n'.join(sections) + '\n'


def main():
    catalog = json.loads((REPOSITORY / 'catalog/catalog.json').read_text())
    atlas.validate(catalog)
    output = POC / 'dist'
    atlas.require((output / 'index.html').is_file(), 'Build the LikeC4 HTML before preparing its rendered page')
    # The CLI writes README.md into its project directory. Isolate that output
    # so source files and the authored demo README are never overwritten.
    with tempfile.TemporaryDirectory(prefix='likec4-render-') as directory:
        project = Path(directory)
        shutil.copyfile(POC / 'src/atlas.c4', project / 'atlas.c4')
        cli = POC / 'node_modules/.bin/likec4'
        subprocess.run([str(cli), 'export', 'markdown', str(project)], check=True, cwd=POC)
        exported = (project / 'README.md').read_text()
    text = make_readme(catalog, exported, os.environ.get('GITHUB_SHA', ''))
    (output / 'README.md').write_text(text)
    (output / '.nojekyll').touch()
    print('OK: dist contains the standalone viewer and a GitHub-renderable README.')


if __name__ == '__main__':
    main()
